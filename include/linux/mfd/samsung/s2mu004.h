#ifndef __LINUX_MFD_S2MU004_H
#define __LINUX_MFD_S2MU004_H

#include <linux/bits.h>

/* S2MU004 registers (main block, I2C address 0x3d) */
enum s2mu004_reg {
	S2MU004_REG_CHGR_INT1,
	S2MU004_REG_CHGR_INT2,
	S2MU004_REG_CHGR_INT1M,
	S2MU004_REG_CHGR_INT2M,

	S2MU004_REG_AFC_INT,
	S2MU004_REG_AFC_INTM,

	S2MU004_REG_MUIC_INT1,
	S2MU004_REG_MUIC_INT2,
	S2MU004_REG_MUIC_INT1M,
	S2MU004_REG_MUIC_INT2M,

	S2MU004_REG_CHGR_STATUS0,
	S2MU004_REG_CHGR_STATUS1,
	S2MU004_REG_CHGR_STATUS2,
	S2MU004_REG_CHGR_STATUS3,
	S2MU004_REG_CHGR_STATUS4,
	S2MU004_REG_CHGR_STATUS5,
	S2MU004_REG_CHGR_CTRL0,
	S2MU004_REG_CHGR_CTRL1,
	S2MU004_REG_CHGR_CTRL2,
	S2MU004_REG_CHGR_CTRL3,
	S2MU004_REG_CHGR_CTRL4,
	S2MU004_REG_CHGR_CTRL5,
	S2MU004_REG_CHGR_CTRL6,
	S2MU004_REG_CHGR_CTRL7,
	S2MU004_REG_CHGR_CTRL8,
	S2MU004_REG_CHGR_CTRL9,
	S2MU004_REG_CHGR_CTRL10,
	S2MU004_REG_CHGR_CTRL11,
	S2MU004_REG_CHGR_CTRL12,
	S2MU004_REG_CHGR_CTRL13,
	S2MU004_REG_CHGR_CTRL14,
	S2MU004_REG_CHGR_CTRL15,
	S2MU004_REG_CHGR_CTRL16,
	S2MU004_REG_CHGR_CTRL17,
	S2MU004_REG_CHGR_CTRL18,
	S2MU004_REG_CHGR_CTRL19,
	S2MU004_REG_CHGR_CTRL20,

	S2MU004_REG_ID = 0x82,
};

/* S2MU004_REG_CHGR_STATUS0 */
#define S2MU004_CHGR_CHGIN_STS		GENMASK(7, 5)
#define S2MU004_CHGR_CHGIN_STS_VALID	5
#define S2MU004_CHGR_CHGIN_STS_VALID_ALT 3

/* S2MU004_REG_CHGR_STATUS1 */
#define S2MU004_CHGR_SELF_DISCHG	BIT(7)
#define S2MU004_CHGR_FAULT		GENMASK(6, 3)
#define S2MU004_CHGR_FAULT_PRECHG	1
#define S2MU004_CHGR_FAULT_FASTCHG	2
#define S2MU004_CHGR_FAULT_WD_SUSPEND	3
#define S2MU004_CHGR_FAULT_WD_RESET	4
#define S2MU004_CHGR_FAULT_TSD		5
#define S2MU004_CHGR_FAULT_TFB		6
#define S2MU004_CHGR_TOPOFF		BIT(1)
#define S2MU004_CHGR_DONE		BIT(0)

/* S2MU004_REG_CHGR_CTRL0 */
#define S2MU004_CHGR_EN_CHG		BIT(7)
#define S2MU004_CHGR_OP_MODE		GENMASK(3, 0)
#define S2MU004_CHGR_OP_MODE_BUCK	1
#define S2MU004_CHGR_OP_MODE_CHG	3

/* S2MU004_REG_CHGR_CTRL13 */
#define S2MU004_CHGR_WDT_EN		BIT(1)
#define S2MU004_CHGR_WDT_AP_RESET	BIT(0)

/* S2MU004_REG_CHGR_CTRL14 */
#define S2MU004_CHGR_WDT_CLR		BIT(0)

/* S2MU004_REG_ID */
#define S2MU004_ID_MASK			GENMASK(7, 4)

#endif /* __LINUX_MFD_S2MU004_H */
